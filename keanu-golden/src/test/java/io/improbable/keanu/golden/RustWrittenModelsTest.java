package io.improbable.keanu.golden;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.improbable.keanu.algorithms.graphtraversal.VertexValuePropagation;
import io.improbable.keanu.network.BayesianNetwork;
import io.improbable.keanu.network.KeanuProbabilisticModel;
import io.improbable.keanu.tensor.Tensor;
import io.improbable.keanu.tensor.bool.BooleanTensor;
import io.improbable.keanu.tensor.dbl.DoubleTensor;
import io.improbable.keanu.tensor.intgr.IntegerTensor;
import io.improbable.keanu.util.io.JsonLoader;
import io.improbable.keanu.util.io.ProtobufLoader;
import io.improbable.keanu.vertices.Vertex;
import io.improbable.keanu.vertices.VertexLabel;
import org.junit.Test;

import java.io.ByteArrayInputStream;
import java.io.File;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Iterator;
import java.util.List;
import java.util.Map;

import static org.junit.Assert.assertTrue;

/**
 * Loads every model the Rust implementation wrote (rust/keanu-io/tests/fixtures/rust-written, generated by the
 * keanu-io round_trip test) with the Java loaders, recomputes every deterministic vertex with Java's operations, and
 * checks the log probability and the value of every labelled vertex against what Rust computed.
 */
public class RustWrittenModelsTest {

    private static final double TOLERANCE = 1e-10;

    private static File fixtures() {
        return new File(System.getProperty("keanu.rustWrittenFixtures"));
    }

    @Test
    public void everyRustWrittenModelLoadsInJavaAndGivesTheSameValues() throws Exception {
        JsonNode expected = new ObjectMapper().readTree(new File(fixtures(), "expected.json"));
        List<String> problems = new ArrayList<>();
        int checked = 0;
        for (Iterator<Map.Entry<String, JsonNode>> it = expected.fields(); it.hasNext(); ) {
            Map.Entry<String, JsonNode> model = it.next();
            String name = model.getKey();
            byte[] pb = Files.readAllBytes(new File(fixtures(), name + ".pb").toPath());
            byte[] json = Files.readAllBytes(new File(fixtures(), name + ".json").toPath());
            check(name + " (protobuf)", new ProtobufLoader().loadNetwork(new ByteArrayInputStream(pb)), model.getValue(), problems);
            check(name + " (json)", new JsonLoader().loadNetwork(new ByteArrayInputStream(json)), model.getValue(), problems);
            checked++;
        }
        assertTrue("expected the golden models and the Rust-built model", checked >= 8);
        assertTrue(problems.size() + " problems:\n" + String.join("\n", problems), problems.isEmpty());
    }

    private static void check(String context, BayesianNetwork network, JsonNode expected, List<String> problems) {
        // recompute every deterministic vertex from the loaded latent and observed values
        VertexValuePropagation.eval(network.getAllVertices());

        double logProb = new KeanuProbabilisticModel(network).logProb();
        if (!close(logProb, number(expected.get("logProb")))) {
            problems.add(context + " logProb " + logProb + " != " + expected.get("logProb"));
        }

        for (Iterator<Map.Entry<String, JsonNode>> it = expected.get("values").fields(); it.hasNext(); ) {
            Map.Entry<String, JsonNode> entry = it.next();
            Vertex<?, ?> vertex = network.getVertexByLabel(VertexLabel.parseLabel(entry.getKey()));
            if (vertex == null) {
                problems.add(context + " no vertex labelled " + entry.getKey());
                continue;
            }
            Tensor<?, ?> value = (Tensor<?, ?>) vertex.getValue();
            long[] shape = new long[entry.getValue().get("shape").size()];
            for (int i = 0; i < shape.length; i++) {
                shape[i] = entry.getValue().get("shape").get(i).asLong();
            }
            double[] data = flatten(value);
            JsonNode expectedData = entry.getValue().get("data");
            if (!Arrays.equals(shape, value.getShape()) || data.length != expectedData.size()) {
                problems.add(context + " " + entry.getKey() + " shape " + Arrays.toString(value.getShape()) + " != " + Arrays.toString(shape));
                continue;
            }
            for (int i = 0; i < data.length; i++) {
                if (!close(data[i], number(expectedData.get(i)))) {
                    problems.add(context + " " + entry.getKey() + "[" + i + "] " + data[i] + " != " + expectedData.get(i));
                    break;
                }
            }
        }
    }

    private static double[] flatten(Tensor<?, ?> value) {
        if (value instanceof DoubleTensor) {
            return ((DoubleTensor) value).asFlatDoubleArray();
        } else if (value instanceof IntegerTensor) {
            return Arrays.stream(((IntegerTensor) value).asFlatIntegerArray()).asDoubleStream().toArray();
        } else {
            Boolean[] booleans = ((BooleanTensor) value).asFlatArray();
            double[] out = new double[booleans.length];
            for (int i = 0; i < booleans.length; i++) {
                out[i] = booleans[i] ? 1.0 : 0.0;
            }
            return out;
        }
    }

    private static double number(JsonNode node) {
        if (node.isNumber()) {
            return node.asDouble();
        }
        switch (node.asText()) {
            case "NaN":
                return Double.NaN;
            case "inf":
                return Double.POSITIVE_INFINITY;
            case "-inf":
                return Double.NEGATIVE_INFINITY;
            default:
                throw new IllegalArgumentException("Not a number: " + node);
        }
    }

    private static boolean close(double actual, double expected) {
        return Double.compare(actual, expected) == 0 || Math.abs(actual - expected) <= TOLERANCE * Math.max(1.0, Math.abs(expected));
    }
}
